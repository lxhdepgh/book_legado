/// 把引擎当**子进程**拉起来：启动后端子进程 → 读握手行 → 建立 RPC 连接。
///
/// 支持的引擎来源（优先级从高到低）：
/// 1. **嵌入式 Go 二进制**：编译期编码为 base64，运行时自动提取到同目录
/// 2. **独立 Go 可执行文件**：`legodo_server{ext}` 位于 Flutter exe 同级
/// 3. **Python 子进程**（开发模式）：`python main.py --serve`
/// 4. **FakeEngine**（测试模式）：`--dart-define=LEGODO_FAKE_ENGINE=1`
library;

import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'engine_endpoint.dart';
import 'envelope.dart';

const String _handshakePrefix = 'LEGODO_GATEWAY ';

// ---------------------------------------------------------------------------
// Compile-time constants from environment / generated code
// ---------------------------------------------------------------------------

/// Embedded Go binary as base64 parts (generated by _embed_go_binary.py at build time).
/// If no embedded payload exists, this is empty and the embed path is skipped.
const String _goBackendBase64Parts = String.fromEnvironment('GO_BACKEND_BASE64');
const bool _useFakeEngine = bool.fromEnvironment('LEGODO_FAKE_ENGINE');

// ---------------------------------------------------------------------------
// Path helpers
// ---------------------------------------------------------------------------

/// Flutter 可执行文件的绝对路径。
String get _flutterExePath => Platform.resolvedExecutable;

/// Flutter 可执行文件所在的目录。
String get _flutterDir => File(_flutterExePath).parent.path;

/// Go 二进制在同目录的完整路径（根据平台扩展名）。
String _goBinaryPath(String dir) {
  final ext = Platform.isWindows ? '.exe' : '';
  return '$dir/legodo_server$ext';
}

// ---------------------------------------------------------------------------
// Embedded Go extraction
// ---------------------------------------------------------------------------

/// 从嵌入的 base64 解码并写入磁盘，返回写好的路径。
Future<String?> _extractEmbeddedGo() async {
  // 没有嵌入数据直接跳过（String.fromEnvironment('GO_BACKEND_BASE64') returns '' if not provided）
  if (_goBackendBase64Parts.isEmpty) return null;

  // 如果同目录已有独立的 legodo_server（之前提取过、未删除），直接用
  final siblingPath = _goBinaryPath(_flutterDir);
  if (File(siblingPath).existsSync()) {
    return siblingPath;
  }

  // 需要临时目录来写 — 优先用 Flutter exe 同级目录，失败则退到 system temp
  String writeDir;
  try {
    // 尝试在 flutter exe 目录下创建一个 .legodo 隐藏子目录
    final hiddenDir = pjoin(_flutterDir, '.legodo');
    final dir = Directory(hiddenDir);
    if (!dir.existsSync()) {
      dir.createSync(recursive: true);
    }
    writeDir = hiddenDir;
  } on Object {
    // 写不进 exe 目录（权限不足、只读介质等），退到系统临时目录
    writeDir = Directory.systemTemp.absolute.path;
  }

  final targetPath = pjoin(writeDir, 'legodo_server${Platform.isWindows ? '.exe' : ''}');

  // base64 decode
  // 移除空白字符
  final fullB64 = _goBackendBase64Parts.replaceAll(RegExp(r'\s+'), '');

  if (fullB64.isEmpty) return null;

  Uint8List bytes;
  try {
    bytes = base64.decode(fullB64);
  } on Object catch (e) {
    print('[WARN] Failed to decode embedded Go binary base64: $e');
    return null;
  }

  // 检查是否已经是原始 gzip/zlib 格式（头部为 0x78 9c 或 0x78 01 等）
  // Go 默认用 gzip 压缩，但这里我们存的就是纯二进制
  try {
    File(targetPath).writeAsBytesSync(bytes, flush: true);
    File(targetPath).setAccessTime(DateTime.now());

    // 确保可执行
    if (!Platform.isWindows) {
      Process.runSync('chmod', ['+x', targetPath]);
    }
    return targetPath;
  } on Object catch (e) {
    print('[WARN] Failed to write embedded Go binary: $e');
    return null;
  }
}

String pjoin(String a, String b) => a.endsWith('/') || a.endsWith('\\') ? '$a$b' : '$a/$b';

// ---------------------------------------------------------------------------
// Launch helper
// ---------------------------------------------------------------------------

/// 给一个已有的 Go 可执行文件路径，拉起它并等待握手行。
Future<StartedEngine> _launchServerProcess(String serverPath) async {
  final serverFile = File(serverPath);
  if (!serverFile.existsSync()) {
    throw EngineFailure(
      EngineFailureKind.unavailable,
      'Go 后端可执行文件不存在: $serverPath',
    );
  }

  final process = await Process.start(
    serverPath,
    [],
    workingDirectory: _flutterDir,
  );

  final handshake = Completer<EngineEndpoint>();
  final stderrTail = <String>[];

  process.stdout
      .transform(const Utf8Decoder(allowMalformed: true))
      .listen((chunk) {
    for (final line in const LineSplitter().convert(chunk)) {
      if (!line.startsWith(_handshakePrefix) || handshake.isCompleted) continue;
      try {
        final json = jsonDecode(line.substring(_handshakePrefix.length));
        if (json is Map<String, Object?>) {
          handshake.complete(EngineEndpoint.fromHandshake(json));
        }
      } on FormatException catch (exc) {
        handshake.completeError(EngineFailure(
            EngineFailureKind.transport, '握手行不是合法 JSON：${exc.message}'));
      }
    }
  });

  process.stderr
      .transform(const Utf8Decoder(allowMalformed: true))
      .listen((chunk) {
    for (final line in const LineSplitter().convert(chunk)) {
      stderrTail.add(line);
      if (stderrTail.length > 40) stderrTail.removeAt(0);
    }
  });

  final endpoint = await handshake.future.timeout(
    const Duration(seconds: 60),
    onTimeout: () {
      throw EngineFailure(EngineFailureKind.timeout,
          '60s 没等到 $_handshakePrefix 那一行（stderr：${stderrTail.join(' | ')}）');
    },
  );

  return StartedEngine(process: process, endpoint: endpoint, stderrTail: stderrTail);
}

/// 清理子进程（与 bootstrap.dart 中的 _forceKillProcess 逻辑一致）。
Future<void> _forceKillProcess(Process process) async {
  if (process.exitCode != null) return;

  process.kill(ProcessSignal.sigterm);
  try {
    await process.exitCode.timeout(const Duration(seconds: 2));
    return;
  } on TimeoutException {}

  if (Platform.isWindows) {
    try {
      final pid = process.pid;
      await Process.run('taskkill', ['/F', '/T', '/PID', '$pid']);
      await process.exitCode.timeout(const Duration(seconds: 1));
    } on Object {}
  } else {
    process.kill(ProcessSignal.sigkill);
    try {
      await process.exitCode.timeout(const Duration(seconds: 1));
    } on TimeoutException {}
  }
}

// ---------------------------------------------------------------------------
// Main entry point
// ---------------------------------------------------------------------------

class StartedEngine {
  StartedEngine({required this.process, required this.endpoint, required this.stderrTail});

  final Process process;
  final EngineEndpoint endpoint;

  /// 子进程的最后几行 stderr。
  final List<String> stderrTail;
}

class EngineProcess {
  static const Duration defaultTimeout = Duration(seconds: 60);

  /// 启动后端引擎。按优先级尝试：
  /// 1. Fake engine (test mode)
  /// 2. 嵌入 Go → 提取并启动
  /// 3. 独立 Go 二进制 → 启动
  /// 4. Python 子进程 (dev mode)
  static Future<StartedEngine> start({
    String? python,
    String? mainPy,
    Duration timeout = defaultTimeout,
    List<String> extraArgs = const [],
    Map<String, String> environment = const {},
  }) async {
    // Fake engine — 不拉起子进程
    if (_useFakeEngine) {
      throw EngineFailure(EngineFailureKind.unavailable, 'fake engine requested');
    }

    String? serverPath;

    // 路径 A: 嵌入 Go 二进制（base64 编码在编译期常量中）
    serverPath = await _extractEmbeddedGo();

    // 路径 B: 独立 Go 可执行文件（同级目录）
    if (serverPath == null) {
      final candidate = _goBinaryPath(_flutterDir);
      if (File(candidate).existsSync()) {
        serverPath = candidate;
      }
    }

    // 路径 C: Python 子进程（开发模式）
    if (serverPath == null) {
      final interpreter = python ?? _fromEnvironment('LEGODO_PYTHON');
      final script = mainPy ?? _fromEnvironment('LEGODO_MAIN');
      if (interpreter != null && script != null) {
        final process = await Process.start(interpreter, <String>[
          script, '--serve', '--port', '0',
          '--idle-seconds', '15', ...extraArgs,
        ], workingDirectory: File(script).parent.path, environment: environment);

        return _waitForHandshake(process, timeout);
      }
    }

    // 所有路径都失败
    final msg = serverPath != null
        ? 'Go 后端可执行文件存在但未输出握手行'
        : '当前环境不支持拉起引擎：没有找到 Go 后端或 Python 解释器。\n'
            '构建时给 --dart-define=LEGODO_PYTHON=…&LEGODO_MAIN=…，\n'
            '或使用 build_release.py 构建完整版本（含 Go 后端）。';

    throw EngineFailure(EngineFailureKind.unavailable, msg);
  }

  /// 通用握手等待逻辑，复用 stdout/stderr 监听。
  static Future<StartedEngine> _waitForHandshake(
    Process process,
    Duration timeout,
  ) async {
    final handshake = Completer<EngineEndpoint>();
    final stderrTail = <String>[];

    process.stdout.transform(const Utf8Decoder(allowMalformed: true)).listen((chunk) {
      for (final line in const LineSplitter().convert(chunk)) {
        if (!line.startsWith(_handshakePrefix) || handshake.isCompleted) continue;
        try {
          final json = jsonDecode(line.substring(_handshakePrefix.length));
          if (json is Map<String, Object?>) {
            handshake.complete(EngineEndpoint.fromHandshake(json));
          }
        } on FormatException catch (exc) {
          handshake.completeError(EngineFailure(
              EngineFailureKind.transport, '握手行不是合法 JSON：${exc.message}'));
        }
      }
    });

    process.stderr.transform(const Utf8Decoder(allowMalformed: true)).listen((chunk) {
      for (final line in const LineSplitter().convert(chunk)) {
        stderrTail.add(line);
        if (stderrTail.length > 40) stderrTail.removeAt(0);
      }
    });

    try {
      final endpoint = await handshake.future.timeout(timeout, onTimeout: () {
        throw EngineFailure(EngineFailureKind.timeout,
            '${timeout.inSeconds}s 没等到 $_handshakePrefix 那一行'
            '（子进程 stderr 尾部：${stderrTail.join(' | ')}）');
      });
      return StartedEngine(process: process, endpoint: endpoint, stderrTail: stderrTail);
    } catch (_) {
      await _forceKillProcess(process);
      rethrow;
    }
  }

  static String? _fromEnvironment(String key) {
    final fromBuild = switch (key) {
      'LEGODO_PYTHON' => _pythonFromBuild,
      'LEGODO_MAIN' => _mainFromBuild,
      _ => '',
    };
    if (fromBuild.isNotEmpty) return fromBuild;
    final fromRuntime = Platform.environment[key];
    return (fromRuntime == null || fromRuntime.isEmpty) ? null : fromRuntime;
  }
}

// Legacy compile-time constants kept for compat with old --dart-define usage.
const String _pythonFromBuild = String.fromEnvironment('LEGODO_PYTHON');
const String _mainFromBuild = String.fromEnvironment('LEGODO_MAIN');
